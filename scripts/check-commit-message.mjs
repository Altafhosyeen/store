#!/usr/bin/env node
/** Conventional Commit validation. */
import { readFileSync } from "node:fs";

const TYPES = [
  "feat",
  "fix",
  "refactor",
  "perf",
  "test",
  "docs",
  "style",
  "build",
  "ci",
  "chore",
  "revert",
];

const MAX_SUBJECT_LENGTH = 100;

const VAGUE_SUBJECTS = [
  "fix stuff",
  "changes",
  "update",
  "updates",
  "wip",
  "misc",
  "fixes",
  "stuff",
  "temp",
];

const messageFilePath = process.argv[2];

if (!messageFilePath) {
  process.stderr.write("check-commit-message.mjs: no commit message file given\n");
  process.exit(1);
}

const rawMessage = readFileSync(messageFilePath, "utf8");

const subject = rawMessage
  .split("\n")
  .find((line) => line.trim() && !line.startsWith("#"))
  ?.trim();

const fail = (reason) => {
  process.stderr.write(
    [
      "",
      `Invalid commit message: ${reason}`,
      "",
      "Expected format:  <type>(<scope>): <subject>",
      `Allowed types:    ${TYPES.join(", ")}`,
      "",
      "Examples:",
      "  feat(products): add product approval flow",
      "  fix(cart): handle expired session redirect",
      "",
    ].join("\n"),
  );
  process.exit(1);
};

if (!subject) {
  fail("the message is empty");
}

// Merge and revert commits are generated by git itself.
if (/^(Merge|Revert)\b/.test(subject)) {
  process.exit(0);
}

const match = /^([a-z]+)(?:\(([^)]+)\))?(!)?: (.+)$/.exec(subject);

if (!match) {
  fail(`"${subject}" does not match <type>(<scope>): <subject>`);
}

const [, type, , , description] = match;

if (!TYPES.includes(type)) {
  fail(`"${type}" is not an allowed type`);
}

if (subject.length > MAX_SUBJECT_LENGTH) {
  fail(`the subject is ${subject.length} characters (max ${MAX_SUBJECT_LENGTH})`);
}

if (description.endsWith(".")) {
  fail("the subject must not end with a period");
}

if (VAGUE_SUBJECTS.includes(description.trim().toLowerCase())) {
  fail(`"${description}" is too vague; describe what actually changed`);
}
